// Package ci renders a GitHub Actions workflow that runs a codenv project on
// windows-latest. It is a pure string factory so it can be tested without a
// project on disk.
package ci

import (
	"fmt"
	"strings"
)

type RenderOptions struct {
	// CodenvRef is the codenv release tag to install, "latest" by default.
	CodenvRef string
	// Command is the command list the workflow runs inside the environment,
	// e.g. ["run", "test"].
	Command []string
}

// normalized fills defaults for CodenvRef and Command.
func normalized(opt RenderOptions) RenderOptions {
	if strings.TrimSpace(opt.CodenvRef) == "" {
		opt.CodenvRef = "latest"
	}
	if len(opt.Command) == 0 {
		opt.Command = []string{"run", "test"}
	}
	return opt
}

// downloadURL builds the codenv zip URL for the runner architecture. The
// codenv release workflow attaches codenv-windows-x64.zip and
// codenv-windows-arm64.zip; runner.arch is X64 or ARM64 on windows runners.
func downloadURL(ref string) string {
	asset := "codenv-windows-${{ runner.arch == 'X64' && 'x64' || 'arm64' }}.zip"
	if ref == "latest" {
		return "https://github.com/Tijani127/codenv/releases/latest/download/" + asset
	}
	return fmt.Sprintf("https://github.com/Tijani127/codenv/releases/download/%s/", ref) + asset
}

// Render produces the contents of .github/workflows/codenv.yml.
func Render(opt RenderOptions) ([]byte, error) {
	opt = normalized(opt)
	ref := opt.CodenvRef
	cmd := strings.Join(opt.Command, " ")

	var w strings.Builder
	w.WriteString("# Generated by codenv. Regenerate with:\n")
	w.WriteString("#   codenv generate ci\n")
	w.WriteString("name: codenv\n\n")
	w.WriteString("on:\n")
	w.WriteString("  push:\n")
	w.WriteString("    branches: [main]\n")
	w.WriteString("  pull_request:\n\n")

	// codenv keeps its store, buckets and binary under one root. runner.temp
	// is a writable, workflow-consistent location that actions/cache can
	// reference safely (GitHub does not expand $env: vars in `path:`).
	w.WriteString("env:\n")
	w.WriteString("  CODEENV_HOME: ${{ runner.temp }}\\codenv\n\n")

	w.WriteString("jobs:\n")
	w.WriteString("  codenv:\n")
	w.WriteString("    runs-on: windows-latest\n")
	w.WriteString("    steps:\n")
	w.WriteString("      - uses: actions/checkout@v4\n\n")
	w.WriteString("      - name: Cache Scoop buckets\n")
	w.WriteString("        uses: actions/cache@v4\n")
	w.WriteString("        with:\n")
	w.WriteString("          path: ${{ runner.temp }}\\codenv\\store\\buckets\n")
	w.WriteString("          key: codenv-buckets-v1\n\n")
	w.WriteString("      - name: Cache store\n")
	w.WriteString("        uses: actions/cache@v4\n")
	w.WriteString("        with:\n")
	w.WriteString("          path: ${{ runner.temp }}\\codenv\\store\\apps\n")
	w.WriteString("          key: codenv-store-${{ runner.arch }}-${{ hashFiles('codenv.lock.json') }}\n")
	w.WriteString("          restore-keys: |\n")
	w.WriteString("            codenv-store-${{ runner.arch }}-\n\n")
	w.WriteString("      - name: Install codenv\n")
	w.WriteString("        shell: pwsh\n")
	w.WriteString("        run: |\n")
	w.WriteString("          $ErrorActionPreference = 'Stop'\n")
	w.WriteString("          $dest = \"$env:CODEENV_HOME\\bin\"\n")
	w.WriteString("          New-Item -ItemType Directory -Force $dest | Out-Null\n")
	w.WriteString(fmt.Sprintf("          Invoke-WebRequest -Uri %q -OutFile \"$env:RUNNER_TEMP\\codenv.zip\" -UseBasicParsing\n", downloadURL(ref)))
	w.WriteString("          Expand-Archive \"$env:RUNNER_TEMP\\codenv.zip\" -DestinationPath $dest -Force\n")
	w.WriteString("          Add-Content $env:GITHUB_PATH $dest\n\n")
	w.WriteString("      - name: Prepare environment\n")
	w.WriteString("        run: codenv install\n")
	w.WriteString("        env:\n")
	w.WriteString("          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}\n\n")
	w.WriteString("      - name: Run\n")
	w.WriteString(fmt.Sprintf("        run: codenv %s\n", cmd))
	return []byte(w.String()), nil
}
